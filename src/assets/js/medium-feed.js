/**
 * medium-feed.js
 * Fetches Medium articles and renders them as Zelio blog cards.
 *
 * Strategy (tiered, most-reliable first):
 *  0. Static HTML     -> gulp renderBlogCards bakes the cards straight into
 *                        the served HTML and marks the container with
 *                        data-static-rendered. Crawlers get real content with
 *                        no JS, so when that marker is present this script
 *                        stands down entirely.
 *  1. Build snapshot  -> static JSON generated at build time by gulp
 *                        (dist/assets/js/blog-feed.json). Fresh as of the
 *                        last deploy, same-origin, no CORS proxy needed.
 *  2. rss2json        -> runtime fallback (free tier caches aggressively,
 *                        may be stale for hours; `thumbnail` is often empty
 *                        for Medium, so we extract the first <img> from
 *                        the item content)
 *
 * Targets:
 *   #medium-recent-blog  → Homepage "Recent Blog" section (limit: 3)
 *   #medium-blog-list    → Blog List page (limit: 9)
 */
(function () {
    'use strict';

    /* =========================================================
     * CONFIG
     * ========================================================= */
    var CONFIG = {
        username: 'ari-dev',
        homeLimit: 3,
        listLimit: 9,
        // Tier 1: build-time snapshot generated by gulp fetchBlogFeed
        snapshotUrl: 'assets/js/blog-feed.json',
        // Tier 2: rss2json -> returns JSON, cached (free tier)
        rss2jsonUrl: 'https://api.rss2json.com/v1/api.json?rss_url=https%3A%2F%2Fmedium.com%2Ffeed%2F%40ari-dev',
        fallbackImages: [
            'https://picsum.photos/seed/ari-blog-1/800/500',
            'https://picsum.photos/seed/ari-blog-2/800/500',
            'https://picsum.photos/seed/ari-blog-3/800/500',
            'https://picsum.photos/seed/ari-blog-4/800/500',
            'https://picsum.photos/seed/ari-blog-5/800/500',
            'https://picsum.photos/seed/ari-blog-6/800/500',
            'https://picsum.photos/seed/ari-blog-7/800/500',
            'https://picsum.photos/seed/ari-blog-8/800/500',
            'https://picsum.photos/seed/ari-blog-9/800/500',
            'https://picsum.photos/seed/ari-blog-10/800/500',
            'https://picsum.photos/seed/ari-blog-11/800/500',
            'https://picsum.photos/seed/ari-blog-12/800/500',
        ],
    };

    /* =========================================================
     * HELPERS
     * ========================================================= */

    /** Extract first real <img> src, skipping tracking 1x1 pixels */
    function extractImageFromContent(html) {
        if (!html) return null;
        var regex = /<img[^>]+src="([^"]+)"[^>]*/gi;
        var match;
        while ((match = regex.exec(html)) !== null) {
            var tag = match[0];
            if (tag.indexOf('width="1"') !== -1 || tag.indexOf('height="1"') !== -1) continue;
            if (match[1].indexOf('stat?event') !== -1) continue;
            return match[1];
        }
        return null;
    }

    function getThumbnail(item, index) {
        if (item.thumbnail && item.thumbnail.trim().length > 0) return item.thumbnail;
        return CONFIG.fallbackImages[index % CONFIG.fallbackImages.length];
    }

    function getTag(item) {
        if (item.categories && item.categories.length > 0) {
            var tags = item.categories.filter(function (c) { return c && c.trim().length > 0; });
            if (tags.length > 0) return tags[0];
        }
        return 'Article';
    }

    function formatDate(pubDate, content) {
        var date = new Date(pubDate);
        var options = { year: 'numeric', month: 'short', day: 'numeric' };
        var dateStr = isNaN(date.getTime()) ? '' : date.toLocaleDateString('en-US', options);
        var wordCount = (content || '').replace(/<[^>]+>/g, '').split(/\s+/).filter(Boolean).length;
        var minutes = Math.max(1, Math.round(wordCount / 200));
        return (dateStr ? dateStr + ' \u2022 ' : '') + minutes + ' min read';
    }

    function buildDescription(content) {
        var plain = (content || '').replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();
        if (plain.length > 110) return plain.substring(0, 107) + '...';
        return plain || 'Read more on Medium.';
    }

    function escapeHtml(str) {
        return String(str)
            .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
            .replace(/"/g, '&quot;').replace(/'/g, '&#039;');
    }

    function escapeAttr(str) {
        return String(str).replace(/"/g, '&quot;');
    }

    /* =========================================================
     * SKELETON LOADER
     * ========================================================= */
    function renderSkeletons(container, count) {
        if (!document.getElementById('medium-skeleton-styles')) {
            var style = document.createElement('style');
            style.id = 'medium-skeleton-styles';
            style.textContent =
                '@keyframes medium-pulse{0%,100%{opacity:1}50%{opacity:0.35}}' +
                '.medium-skeleton{background:var(--tc-neutral-800,#2a2a3e);border-radius:4px;animation:medium-pulse 1.5s ease-in-out infinite}';
            document.head.appendChild(style);
        }
        var html = '';
        for (var i = 0; i < count; i++) {
            var delay = (i * 0.15) + 's';
            html +=
                '<div class="col-lg-4">' +
                    '<div class="blog-card rounded-4 mb-lg-3 mb-md-5 mb-3">' +
                        '<div class="blog-card__image position-relative">' +
                            '<div class="zoom-img rounded-3 overflow-hidden">' +
                                '<div class="medium-skeleton w-100" style="height:220px;animation-delay:' + delay + '"></div>' +
                            '</div>' +
                        '</div>' +
                        '<div class="blog-card__content position-relative text-center mt-4">' +
                            '<div class="medium-skeleton mx-auto mb-3" style="height:11px;width:55%;animation-delay:' + delay + '"></div>' +
                            '<div class="medium-skeleton mx-auto mb-2" style="height:17px;width:80%;animation-delay:' + delay + '"></div>' +
                            '<div class="medium-skeleton mx-auto" style="height:12px;width:65%;animation-delay:' + delay + '"></div>' +
                        '</div>' +
                    '</div>' +
                '</div>';
        }
        container.innerHTML = html;
    }

    /* =========================================================
     * CARD TEMPLATE â€” mirrors blog-card.html structure exactly
     * ========================================================= */
    function renderCard(item, index) {
        var thumbnail   = getThumbnail(item, index);
        var tag         = getTag(item);
        var dateStr     = formatDate(item.pubDate, item.content);
        var description = buildDescription(item.description || item.content);
        var link        = item.link || ('https://medium.com/@' + CONFIG.username);
        var title       = item.title || 'Untitled';
        var fallback    = CONFIG.fallbackImages[index % CONFIG.fallbackImages.length];

        return (
            '<div class="col-lg-4">' +
                '<div class="blog-card rounded-4 mb-lg-3 mb-md-5 mb-3">' +
                    '<div class="blog-card__image position-relative">' +
                        '<div class="zoom-img rounded-3 overflow-hidden">' +
                            '<img class="w-100" src="' + escapeAttr(thumbnail) + '" alt="' + escapeAttr(title) + '" width="400" height="250" loading="lazy" decoding="async" ' +
                                'onerror="this.onerror=null;this.src=\'' + fallback + '\'" />' +
                            '<a class="position-absolute bottom-0 start-0 m-3 text-white-keep btn btn-gradient fw-medium rounded-3 px-3 py-2" ' +
                                'href="' + escapeAttr(link) + '" target="_blank" rel="noopener noreferrer">' +
                                escapeHtml(tag) +
                            '</a>' +
                            '<a href="' + escapeAttr(link) + '" target="_blank" rel="noopener noreferrer" ' +
                                'class="blog-card__link position-absolute top-50 start-50 translate-middle icon-md icon-shape bg-linear-1 rounded-circle" aria-label="Read ' + escapeAttr(title) + ' on Medium">' +
                                '<i class="ri-arrow-right-up-line text-dark"></i>' +
                            '</a>' +
                        '</div>' +
                    '</div>' +
                    '<div class="blog-card__content position-relative text-center mt-4">' +
                        '<span class="blog-card__date fs-7">' + escapeHtml(dateStr) + '</span>' +
                        '<h5 class="blog-card__title">' + escapeHtml(title) + '</h5>' +
                        '<p class="blog-card__description fs-6">' + escapeHtml(description) + '</p>' +
                        '<a href="' + escapeAttr(link) + '" target="_blank" rel="noopener noreferrer" ' +
                            'class="link-overlay position-absolute top-0 start-0 w-100 h-100" aria-label="Read article: ' + escapeAttr(title) + '"></a>' +
                    '</div>' +
                '</div>' +
            '</div>'
        );
    }

    /* =========================================================
     * ERROR STATE
     * ========================================================= */
    function renderError(container) {
        container.innerHTML =
            '<div class="col-12 text-center py-5">' +
                '<p class="text-200 fs-5 mb-4">Could not load articles right now.</p>' +
                '<a href="https://medium.com/@' + CONFIG.username + '" ' +
                    'target="_blank" rel="noopener noreferrer" class="btn btn-gradient">' +
                    'Read on Medium &nbsp;<i class="ri-external-link-line"></i>' +
                '</a>' +
            '</div>';
    }

    /* =========================================================
     * TIER 1: Build-time snapshot (dist/assets/js/blog-feed.json)
     *         Generated by gulp fetchBlogFeed on every build.
     *         Same-origin, fresh as of the last deploy.
     * ========================================================= */
    function fetchViaSnapshot(limit, onSuccess, onError) {
        fetch(CONFIG.snapshotUrl)
            .then(function (r) {
                if (!r.ok) throw new Error('snapshot HTTP ' + r.status);
                return r.json();
            })
            .then(function (data) {
                if (data.status !== 'ok') throw new Error('snapshot: ' + (data.message || data.status));
                if (!data.items || data.items.length === 0) throw new Error('snapshot: 0 items');
                onSuccess(data.items.slice(0, limit));
            })
            .catch(function (err) {
                console.warn('[medium-feed] snapshot failed:', err.message, '- trying rss2json fallback...');
                onError();
            });
    }

    /* =========================================================
     * TIER 2: Fetch via rss2json -> JSON (cached, may be stale).
     *         rss2json's `thumbnail` field is often empty for
     *         Medium feeds, so extract the first <img> from
     *         item content before rendering.
     * ========================================================= */
    function normalizeRss2jsonItem(item) {
        return Object.assign({}, item, {
            thumbnail: (item.thumbnail && String(item.thumbnail).trim()) || extractImageFromContent(item.content || item.description || '') || ''
        });
    }

    function fetchViaRss2json(limit, onSuccess, onError) {
        fetch(CONFIG.rss2jsonUrl)
            .then(function (r) {
                if (!r.ok) throw new Error('rss2json HTTP ' + r.status);
                return r.json();
            })
            .then(function (data) {
                if (data.status !== 'ok') throw new Error('rss2json: ' + (data.message || data.status));
                if (!data.items || data.items.length === 0) throw new Error('rss2json: 0 items');
                onSuccess(data.items.map(normalizeRss2jsonItem).slice(0, limit));
            })
            .catch(function (err) {
                console.error('[medium-feed] rss2json also failed:', err.message);
                onError();
            });
    }

    /* =========================================================
     * MAIN FETCH - try Tier 1, fallback to Tier 2
     * ========================================================= */
    function fetchFeed(limit, onSuccess, onError) {
        fetchViaSnapshot(
            limit,
            onSuccess,
            function () {
                fetchViaRss2json(limit, onSuccess, onError);
            }
        );
    }

    /* =========================================================
     * INIT
     * ========================================================= */
    /**
     * Fill a card container, unless the build already did it.
     *
     * When gulp renderBlogCards succeeds it writes the cards into the HTML and
     * sets data-static-rendered on the container. Re-fetching the same snapshot
     * to paint the same cards would only add a request and a layout flash, so
     * bail out. The whole client path stays live for a build whose feed fetch
     * failed, where the container ships empty and unmarked.
     */
    function initContainer(id, limit) {
        var container = document.getElementById(id);
        if (!container) return;
        if (container.getAttribute('data-static-rendered') === 'true') return;

        renderSkeletons(container, limit);
        fetchFeed(
            limit,
            function (items) {
                var html = '';
                items.forEach(function (item, i) { html += renderCard(item, i); });
                container.innerHTML = html;
            },
            function () { renderError(container); }
        );
    }

    function initHomeBlog() {
        initContainer('medium-recent-blog', CONFIG.homeLimit);
    }

    function initBlogList() {
        initContainer('medium-blog-list', CONFIG.listLimit);
    }

    /* =========================================================
     * BOOTSTRAP
     * ========================================================= */
    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', function () {
            initHomeBlog();
            initBlogList();
        });
    } else {
        initHomeBlog();
        initBlogList();
    }

})();
